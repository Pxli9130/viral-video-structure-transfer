#!/usr/bin/env node
// Regenerate apps/api/remotion/effects/generated/effect-manifest.ts from the EffectKnowledgeBase.
// Includes ONLY generated effects that: are in the KB, are EXPLICITLY promoted, have validationStatus
// pass|pass_with_preview_blocker, and have their source files present on disk. Static imports only;
// identifiers are sanitized. A default-exported component is imported as a default import.

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { loadEffectKnowledgeBase } from "@vvst/shared";

const ROOT = process.cwd();
const GENERATED_DIR = path.join(ROOT, "apps/api/remotion/effects/generated");
const MANIFEST_PATH = path.join(GENERATED_DIR, "effect-manifest.ts");
const SAFE_ID = /^[a-zA-Z0-9_]+$/;

function sanitizeId(id) {
  return String(id).replace(/[^a-zA-Z0-9_]/g, "_");
}

/** Pure: build the manifest source from a list of {id, componentName, motifFamily} entries. */
export function buildGeneratedManifestSource(entries) {
  const imports = [];
  const body = [];
  for (const e of entries) {
    const local = `Gen_${sanitizeId(e.id)}`;
    imports.push(
      e.defaultExport
        ? `import ${local} from "./${e.id}/index";`
        : `import { ${e.componentName} as ${local} } from "./${e.id}/index";`
    );
    body.push(
      `  ${JSON.stringify(e.id)}: { id: ${JSON.stringify(e.id)}, componentName: ${JSON.stringify(e.componentName)}, motifFamily: ${JSON.stringify(e.motifFamily)}, Component: ${local} },`
    );
  }
  return [
    "// AUTO-GENERATED by scripts/update-generated-effect-manifest.mjs — do not edit by hand.",
    "// Static imports only. Regenerated when a validated generated effect is applied.",
    'import type React from "react";',
    ...imports,
    "",
    "export interface GeneratedEffectManifestEntry {",
    "  id: string;",
    "  componentName: string;",
    "  motifFamily: string;",
    "  // eslint-disable-next-line @typescript-eslint/no-explicit-any",
    "  Component: React.FC<any>;",
    "}",
    "",
    "export const generatedEffectManifest: Record<string, GeneratedEffectManifestEntry> = {",
    ...body,
    "};",
    ""
  ].join("\n");
}

/** Select includable generated effects from the KB (promoted + valid + on-disk + safe identifiers). */
export function selectManifestEntries(kb, generatedDir = GENERATED_DIR) {
  const ok = new Set(["pass", "pass_with_preview_blocker"]);
  return kb.entries
    .filter((e) => e.source === "generated" && e.promoted === true && ok.has(e.validationStatus))
    .filter((e) => SAFE_ID.test(String(e.id)) && /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(String(e.componentName)))
    .filter((e) => existsSync(path.join(generatedDir, e.id, "index.tsx")))
    .map((e) => ({ id: e.id, componentName: e.componentName, motifFamily: e.motifFamily, defaultExport: Boolean(e.defaultExport) }));
}

function main() {
  const kb = loadEffectKnowledgeBase();
  const entries = selectManifestEntries(kb);
  const source = buildGeneratedManifestSource(entries);
  const prev = existsSync(MANIFEST_PATH) ? readFileSync(MANIFEST_PATH, "utf8") : "";
  if (prev !== source) writeFileSync(MANIFEST_PATH, source, "utf8");
  console.log(`[update-generated-effect-manifest] ${entries.length} generated effect(s): [${entries.map((e) => e.id).join(", ")}]`);
}

const isMain = process.argv[1] && path.resolve(process.argv[1]).endsWith("update-generated-effect-manifest.mjs");
if (isMain) main();
